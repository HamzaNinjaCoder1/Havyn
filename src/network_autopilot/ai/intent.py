"""Havyn intent schema, version 1 (S5.1).

This is the contract between the AI layer and the deterministic engine. The
model produces one of these; it never produces a NetworkSpec directly.

Design rules:

- Shape, not policy: like every other model in this package, validation here
  is structural only. Semantic checks (contradictions, missing information,
  unsupported combinations) live in ``lint.py`` and return structured results
  so the caller decides what to do.
- Only verified engine capabilities appear as fields. ``internet.access``
  supports the live-verified shapes (WAN handoff, DSL, cable); anything the
  engine cannot build is not expressible here, and the lint reports it by
  name instead of guessing.
- ``requirements`` doubles as the Requirement Ledger (S5.4 of the blueprint):
  every extracted requirement keeps its id, source, type, priority,
  confidence and dependency list through expansion, so the final network can
  answer "which user requirement produced this configuration?".
- Everything the deterministic engine can decide (switch counts, port
  choices, exact addresses, cable media, positions) is intentionally absent:
  the expander computes those, deterministically.
"""

from __future__ import annotations

import json
from enum import Enum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

INTENT_VERSION = "1"

# Matches core.ids.validate_id: references generated by the expander
# (device ids, link ids, subnet ids) must survive the engine's own id rules.
import re

_ID_RE = re.compile(r"^[a-z][a-z0-9_-]{0,63}$")
_REQ_ID_RE = re.compile(r"^REQ-\d{3,}$")


def _validate_ref(value: str, kind: str) -> str:
    if not isinstance(value, str) or not _ID_RE.match(value):
        raise ValueError(
            f"invalid {kind}: {value!r} (expected lowercase letter first, then "
            f"[a-z0-9_-], max 64 chars)"
        )
    return value


class IntentModel(BaseModel):
    """Base for intent models: strict, frozen, no free-form extras."""

    model_config = ConfigDict(extra="forbid", frozen=True)


class RequirementType(str, Enum):
    CONNECTIVITY = "connectivity"
    SECURITY = "security"
    ADDRESSING = "addressing"
    SERVICE = "service"
    ISOLATION = "isolation"
    OPERATIONAL = "operational"
    CONSTRAINT = "constraint"


class RequirementIntent(IntentModel):
    """One Requirement Ledger entry (blueprint S5.4).

    The ledger is the traceability spine: requirement -> interpretation ->
    design decision -> configuration -> verification -> verdict. ``source``
    points back into the user's prompt or document (e.g. ``"section_8"`` or
    ``"prompt"``); ``confidence`` is the extractor's own confidence, never a
    claim that the requirement was verified.
    """

    id: str
    statement: str = Field(min_length=1)
    source: str | None = None
    type: RequirementType = RequirementType.CONNECTIVITY
    priority: Literal["critical", "high", "normal", "low"] = "normal"
    status: Literal[
        "extracted", "clarified", "planned", "verified", "rejected"
    ] = "extracted"
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    dependencies: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _check(self) -> "RequirementIntent":
        if not _REQ_ID_RE.match(self.id):
            raise ValueError(
                f"requirement id must look like 'REQ-001': {self.id!r}"
            )
        for dep in self.dependencies:
            if not _REQ_ID_RE.match(dep):
                raise ValueError(
                    f"requirement {self.id!r} lists a malformed dependency: {dep!r}"
                )
        if self.status in ("verified", "rejected"):
            raise ValueError(
                f"requirement {self.id!r}: status {self.status!r} is earned by the "
                "engine/verification layer, never stated by the extractor"
            )
        return self


class HostDevice(str, Enum):
    PC = "pc"
    LAPTOP = "laptop"
    PRINTER = "printer"
    IP_PHONE = "ip_phone"
    SMARTPHONE = "smartphone"
    TABLET = "tablet"


WIRELESS_DEVICES = frozenset({HostDevice.LAPTOP, HostDevice.SMARTPHONE, HostDevice.TABLET})


class HostGroupIntent(IntentModel):
    """A group of identical end hosts in one area, attached to one VLAN."""

    id: str
    area: str
    count: int = Field(default=1, ge=1, le=200)
    device: HostDevice = HostDevice.PC
    vlan: str | None = None  # None -> the site's default user VLAN
    addressing: Literal["dhcp", "static"] | None = None  # None -> VLAN default
    # Explicit traceability: which ledger requirements motivated this group.
    requirement_refs: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _check(self) -> "HostGroupIntent":
        _validate_ref(self.id, "host group id")
        _validate_ref(self.area, "area ref")
        if self.vlan is not None:
            _validate_ref(self.vlan, "vlan ref")
        return self


class AreaIntent(IntentModel):
    """One floor / building / zone of a site."""

    id: str
    kind: Literal["floor", "building", "area", "rack"] = "area"
    host_groups: list[HostGroupIntent] = Field(default_factory=list)

    @model_validator(mode="after")
    def _check(self) -> "AreaIntent":
        _validate_ref(self.id, "area id")
        return self


class SiteIntent(IntentModel):
    """One physical site of the network."""

    id: str
    name: str | None = None
    areas: list[AreaIntent] = Field(default_factory=list)

    @model_validator(mode="after")
    def _check(self) -> "SiteIntent":
        _validate_ref(self.id, "site id")
        return self


class VlanIntent(IntentModel):
    """One user-defined VLAN.

    A VLAN with ``site: None`` is instantiated once per site by the expander;
    a VLAN bound to a site exists only there. Exactly one size source must be
    given (``cidr`` fixed by the user, or ``required_hosts`` planned by the
    IPAM) — the same rule the NetworkSpec enforces on subnets.
    """

    id: str
    name: str = Field(min_length=1)
    site: str | None = None
    purpose: str | None = None
    cidr: str | None = None
    required_hosts: int | None = Field(default=None, ge=1)
    dhcp: bool = False
    is_guest: bool = False
    is_management: bool = False

    @model_validator(mode="after")
    def _check(self) -> "VlanIntent":
        _validate_ref(self.id, "vlan id")
        if self.site is not None:
            _validate_ref(self.site, "vlan site ref")
        if (self.cidr is None) == (self.required_hosts is None):
            raise ValueError(
                f"vlan {self.id!r}: exactly one of 'cidr' or 'required_hosts'"
            )
        return self


class ServerIntent(IntentModel):
    """A Server-PT with services, placed in one site's VLAN."""

    id: str
    site: str
    vlan: str | None = None  # None -> the site's server/first VLAN
    services: list[
        Literal["dns", "http", "https", "dhcp", "ftp", "aaa", "ntp", "syslog"]
    ] = Field(default_factory=list)
    # DNS records: name -> ip. HTTP pages: path -> body.
    records: list[dict[str, str]] = Field(default_factory=list)
    pages: dict[str, str] = Field(default_factory=dict)
    requirement_refs: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _check(self) -> "ServerIntent":
        _validate_ref(self.id, "server id")
        _validate_ref(self.site, "server site ref")
        if self.vlan is not None:
            _validate_ref(self.vlan, "server vlan ref")
        return self


class RoutingIntent(IntentModel):
    """Routing intent. The engine owns the exact routes; this states the mode."""

    mode: Literal["connected", "static", "ospf", "eigrp", "rip"] = "connected"
    ospf_area: str = "0"


class InternetIntent(IntentModel):
    """Internet access intent.

    Only verified access shapes are expressible (capability map: S3.A6 NAT/PAT
    overload, S3.F1 cable modem, S3.F3 ISP template). A ``public_server``
    gives flows a destination on the ISP side, which is how the verified
    internet acceptance tests are written.
    """

    access: Literal["wan", "dsl", "cable"] = "wan"
    nat: bool = True
    public_server: bool = False


class FirewallIntent(IntentModel):
    """ASA perimeter intent (verified shapes: T07/T08, S3.C1-C5).

    ``guest_isolation`` asks the expander to emit an address-scoped ACL that
    blocks guest VLANs from reaching internal subnets (verified capability:
    router-acl-enforce / asa-address-scoped).
    """

    enabled: bool
    model: Literal["asa5506", "asa5505"] = "asa5506"
    dmz: bool = False
    guest_isolation: bool = False


class WirelessIntent(IntentModel):
    """One wireless cell: an access point (or wireless router) with clients.

    Clients are ordinary host groups in ``sites[].areas[].host_groups`` whose
    device is wireless (laptop/smartphone/tablet); ``client_group_ids`` names
    which groups this AP serves. The PT association is verified (S3.E1/E3).
    """

    id: str
    site: str
    area: str | None = None
    ssid: str = Field(min_length=1, max_length=32)
    security: Literal["open", "wpa2"] = "wpa2"
    passphrase: str | None = Field(default=None, min_length=8)
    client_group_ids: list[str] = Field(default_factory=list)
    requirement_refs: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _check(self) -> "WirelessIntent":
        _validate_ref(self.id, "wireless id")
        _validate_ref(self.site, "wireless site ref")
        if self.area is not None:
            _validate_ref(self.area, "wireless area ref")
        if self.security == "wpa2" and not self.passphrase:
            raise ValueError(
                f"wireless {self.id!r}: wpa2 needs a passphrase (>= 8 chars)"
            )
        for group in self.client_group_ids:
            _validate_ref(group, "wireless client group ref")
        return self


class IotIntent(IntentModel):
    """IoT devices (verified shape: T14/T16 — cabled, registered, no IP config).

    Packet Tracer provisions IoE things through an IoT registration, not
    desktop IP configuration, so the expander emits cabled devices plus an
    ``IotRegistrationSpec`` — never addressing promises.
    """

    id: str
    site: str
    area: str | None = None
    kind: Literal["smart_led"] = "smart_led"
    count: int = Field(default=1, ge=1, le=50)
    requirement_refs: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _check(self) -> "IotIntent":
        _validate_ref(self.id, "iot id")
        _validate_ref(self.site, "iot site ref")
        if self.area is not None:
            _validate_ref(self.area, "iot area ref")
        return self


class HavynIntent(IntentModel):
    """The Stage 5 intent: everything the AI layer is allowed to decide."""

    intent_version: Literal["1"] = INTENT_VERSION
    name: str = Field(min_length=1)
    description: str | None = None
    # Metadata about the user input the intent was extracted from.
    language: Literal["en", "roman-urdu", "mixed"] | None = None
    source_excerpt: str | None = None

    sites: list[SiteIntent] = Field(min_length=1)
    vlans: list[VlanIntent] = Field(default_factory=list)
    servers: list[ServerIntent] = Field(default_factory=list)
    routing: RoutingIntent = Field(default_factory=RoutingIntent)
    internet: InternetIntent | None = None
    firewall: FirewallIntent | None = None
    wireless: list[WirelessIntent] = Field(default_factory=list)
    iot: list[IotIntent] = Field(default_factory=list)
    requirements: list[RequirementIntent] = Field(default_factory=list)
    constraints: list[str] = Field(default_factory=list)

    # -- structural cross-references (shape only; policy lives in lint) ------

    @model_validator(mode="after")
    def _check_references(self) -> "HavynIntent":
        site_ids = [s.id for s in self.sites]
        if len(site_ids) != len(set(site_ids)):
            raise ValueError("duplicate site ids in intent")
        sites = set(site_ids)

        area_of: dict[str, set[str]] = {}
        groups: dict[str, str] = {}
        for site in self.sites:
            area_ids = [a.id for a in site.areas]
            if len(area_ids) != len(set(area_ids)):
                raise ValueError(f"site {site.id!r}: duplicate area ids")
            area_of[site.id] = set(area_ids)
            for area in site.areas:
                for group in area.host_groups:
                    if group.id in groups:
                        raise ValueError(
                            f"duplicate host group id {group.id!r}"
                        )
                    groups[group.id] = site.id

        vlan_ids = [v.id for v in self.vlans]
        if len(vlan_ids) != len(set(vlan_ids)):
            raise ValueError("duplicate vlan ids in intent")

        for server in self.servers:
            if server.site not in sites:
                raise ValueError(
                    f"server {server.id!r} references unknown site {server.site!r}"
                )

        for cell in self.wireless:
            if cell.site not in sites:
                raise ValueError(
                    f"wireless {cell.id!r} references unknown site {cell.site!r}"
                )
            if cell.area is not None and cell.area not in area_of[cell.site]:
                raise ValueError(
                    f"wireless {cell.id!r} references unknown area {cell.area!r} "
                    f"in site {cell.site!r}"
                )
            for group in cell.client_group_ids:
                owner_site = groups.get(group)
                if owner_site is None:
                    raise ValueError(
                        f"wireless {cell.id!r} references unknown host group {group!r}"
                    )
                if owner_site != cell.site:
                    raise ValueError(
                        f"wireless {cell.id!r} claims group {group!r} from site "
                        f"{owner_site!r}"
                    )

        for thing in self.iot:
            if thing.site not in sites:
                raise ValueError(
                    f"iot {thing.id!r} references unknown site {thing.site!r}"
                )
            if thing.area is not None and thing.area not in area_of[thing.site]:
                raise ValueError(
                    f"iot {thing.id!r} references unknown area {thing.area!r}"
                )

        req_ids = [r.id for r in self.requirements]
        if len(req_ids) != len(set(req_ids)):
            raise ValueError("duplicate requirement ids in intent")
        known_reqs = set(req_ids)
        for ref_chain in (
            [ref for r in self.requirements for ref in r.dependencies],
            [ref for g in groups for ref in []],  # groups have no refs
        ):
            for ref in ref_chain:
                if ref not in known_reqs:
                    raise ValueError(
                        f"requirement dependency references unknown id {ref!r}"
                    )
        for server in self.servers:
            for ref in server.requirement_refs:
                if ref not in known_reqs:
                    raise ValueError(
                        f"server {server.id!r} references unknown requirement {ref!r}"
                    )
        for cell in self.wireless:
            for ref in cell.requirement_refs:
                if ref not in known_reqs:
                    raise ValueError(
                        f"wireless {cell.id!r} references unknown requirement {ref!r}"
                    )
        for thing in self.iot:
            for ref in thing.requirement_refs:
                if ref not in known_reqs:
                    raise ValueError(
                        f"iot {thing.id!r} references unknown requirement {ref!r}"
                    )

        return self

    def host_groups(self) -> list[tuple[SiteIntent, AreaIntent, HostGroupIntent]]:
        """Every (site, area, group) triple in declaration order."""
        out = []
        for site in self.sites:
            for area in site.areas:
                for group in area.host_groups:
                    out.append((site, area, group))
        return out

    # -- serialization -------------------------------------------------------

    def to_json(self, indent: int | None = 2) -> str:
        return json.dumps(self.model_dump(mode="json"), indent=indent, sort_keys=True)

    @classmethod
    def from_json(cls, raw: str | bytes) -> "HavynIntent":
        import pydantic

        try:
            data = json.loads(raw)
        except json.JSONDecodeError as exc:
            raise ValueError(f"intent is not valid JSON: {exc}") from exc
        try:
            return cls.model_validate(data)
        except pydantic.ValidationError as exc:
            raise ValueError(f"intent failed typed validation: {exc}") from exc


def export_json_schema() -> dict:
    """The published JSON Schema for havyn.intent.v1 (versioned, contract)."""
    schema = HavynIntent.model_json_schema()
    return {
        **schema,
        "$schema": "http://json-schema.org/draft-07/schema#",
        "$id": "https://havyn.local/schemas/havyn.intent.v1.json",
        "title": "Havyn Intent Schema v1",
        "description": schema.get("description", ""),
    }
